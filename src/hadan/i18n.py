def normalize_language(value):
    return "en" if str(value or "").lower().split(";")[0].strip().split("-")[0] == "en" else "zh-CN"


def get_language(request):
    explicit = request.query_params.get("lang") or request.cookies.get("quant_lang")
    if explicit:
        return normalize_language(explicit)
    accepted = request.headers.get("accept-language", "").split(",")[0].strip()
    return normalize_language(accepted)


def translate_error(message, request_or_lang="zh-CN"):
    lang = get_language(request_or_lang) if hasattr(request_or_lang, "query_params") else normalize_language(request_or_lang)
    text = str(message)
    if lang == "zh-CN":
        return next((original for original, translated in ERRORS.items() if translated == text), text)
    if text in ERRORS:
        return ERRORS[text]
    if re.search(r"[\u3400-\u9fff]", text):
        return STRINGS[lang]["generic_error"]
    return text


def template_context(request):
    lang = get_language(request)

    def t(key, **values):
        text = STRINGS[lang].get(key, key)
        return text.format(**values) if values else text

    def language_url(value):
        query = [(key, val) for key, val in parse_qsl(request.url.query, keep_blank_values=True) if key != "lang"]
        query.append(("lang", normalize_language(value)))
        return request.url.path + "?" + urlencode(query)

    def format_date(value):
        try:
            return datetime.fromtimestamp(float(value), timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
        except (TypeError, ValueError, OverflowError, OSError):
            return "—"

    return {
        "lang": lang,
        "t": t,
        "language_url": language_url,
        "ui_strings": STRINGS,
        "ui_errors": ERRORS,
        "translate_message": lambda value: translate_error(value, lang),
        "format_date": format_date,
    }
